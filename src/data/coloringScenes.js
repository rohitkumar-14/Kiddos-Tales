/**
 * Returns the best line-art illustration for a given story and page index.
 * Uses handcrafted vector line-arts for instant response, with AI generation fallbacks.
 */
export function getLineArtForStory(story, pageIndex = 0) {
  if (!story) return treehouseLineArt;

  const subject = (story.subject || "").toLowerCase();
  const title = (story.title || "").toLowerCase();
  const storyType = (story.storyType || "").toLowerCase();

  // Match story theme / subject
  if (
    subject.includes("bunny") ||
    subject.includes("rabbit") ||
    title.includes("bunny") ||
    title.includes("benny") ||
    storyType.includes("animal")
  ) {
    return bunnyLineArt;
  }

  if (
    subject.includes("space") ||
    subject.includes("astronaut") ||
    subject.includes("rocket") ||
    title.includes("moon")
  ) {
    return spaceLineArt;
  }

  if (
    subject.includes("castle") ||
    subject.includes("princess") ||
    subject.includes("knight") ||
    subject.includes("dragon") ||
    storyType.includes("fantasy")
  ) {
    return pageIndex % 2 === 0 ? castleLineArt : treehouseLineArt;
  }

  // Default to Treehouse / Nature Adventure
  return treehouseLineArt;
}
